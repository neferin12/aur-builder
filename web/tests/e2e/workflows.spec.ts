import { expect, test } from '@playwright/test'
test('OIDC login, package history, safe logs, decisions, rebuild and logout', async ({ page, request }) => {
  const browserErrors: string[] = []
  page.on('pageerror', error => browserErrors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Packages', exact: true })).toBeVisible()
  await expect(page.getByText('Test Admin')).toBeVisible()
  await page.screenshot({ path: 'test-results/packages.png', fullPage: true })
  await page.getByRole('link', { name: 'example', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'example', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '#1', exact: true }).click()
  await expect(page.getByLabel('Build log')).toContainText('<script>window.pwned=true</script>')
  expect(await page.evaluate(() => 'pwned' in window)).toBe(false)
  await page.goto('/reviews/approve-me')
  await expect(page.getByRole('heading', { name: 'PKGBUILD' })).toBeVisible()
  expect(await page.content()).not.toContain('never-expose-this')
  await expect(page.getByRole('button', { name: 'Approve and queue build' })).toHaveCSS('background-color', 'rgb(65, 9, 98)')
  await page.getByRole('button', { name: 'Approve and queue build' }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('approved')
  await page.goto('/reviews/reject-me')
  await expect(page.getByRole('button', { name: 'Reject', exact: true })).toBeDisabled()
  await page.getByLabel('Comment (required for rejection)').fill('Unsafe packaging change')
  await page.getByRole('button', { name: 'Reject', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('rejected')
  await request.post('/_fixture/finish')
  await page.goto('/build-results/1')
  await page.getByRole('button', { name: 'Rebuild approved revision' }).click()
  await expect(page.getByText('Build queued for the approved revision.')).toBeVisible()
  await page.goto('/admin/users')
  await expect(page.getByRole('heading', { name: 'User access' })).toBeVisible()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Packages', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Signed out' })).toBeVisible()
  expect(browserErrors).toEqual([])
})
